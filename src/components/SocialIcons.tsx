// Function to handle Discord app deep link with 1.5s automatic web fallback
export function openDiscord() {
  const deepLink = SOCIALS.discord.deepLink;
  const webUrl = SOCIALS.discord.url;

  let appOpened = false;

  const onVisibilityChange = () => {
    if (document.hidden) {
      appOpened = true;
    }
  };

  document.addEventListener("visibilitychange", onVisibilityChange);

  // Trigger app protocol handler
  window.location.href = deepLink;

  // Fallback to web profile after ~1.5 seconds if visibility didn't change
  setTimeout(() => {
    document.removeEventListener("visibilitychange", onVisibilityChange);
    if (!appOpened && !document.hidden) {
      window.open(webUrl, "_blank", "noopener,noreferrer");
    }
  }, 1500);
}

// Small floating or inline toast notification
